"""cjf init -- the base: what every other part of the kit assumes is in
place. Run once after installing the kit (install.sh does), and again
after moving the checkout or updating the kit; it changes only what
differs, asks before each change, and backs up a file before its first
change.

    cjf init

What it puts in place:

  ~/.bashrc, ~/.profile    `export PATH=~/.local/bin:$PATH`, unless a
                           line there already puts ~/.local/bin on PATH
  ~/.local/share/curiousj-framekit/init.sh
                           the shell side: Frametop terminals, Homebrew,
                           the shims and ~/.local/bin on PATH, mise, the
                           waypipe function, the tailscale alias. Each
                           part guards itself, so the file stays right
                           as items come and go.
  …/completion.bash, …/completion.zsh
                           cjf's completion, one file per shell, which
                           init.sh sources in that shell only
  ~/.local/share/curiousj-framekit/shims/podman
                           podman for distrobox from the nested desktops
  ~/.bashrc, ~/.zshrc      one marked block at the top that sources
                           init.sh when it exists (~/.zshrc only when
                           that file exists)
  ~/.distroboxrc           a marked block that puts the shims first on
                           PATH for a distrobox export started outside
                           any shell
  the cursor fix           `cjf cursor software auto`: the software
                           cursor and the size entry where nothing was
                           chosen, a choice kept

The host and its distroboxes share the home directory, so the rc files
run in all of them; init.sh is written for that. A `mise activate` line
of your own in an rc file keeps working beside init.sh's, which skips
itself when mise is active already, and is noted so that you can drop
it.
"""

from __future__ import annotations

import os
import re
import subprocess
from importlib import resources
from pathlib import Path

import click

from .. import blocks, cmdline, config, where
from ..cmdline import Options, pass_options
from ..frame import cursor

PATH_LINE = "export PATH=~/.local/bin:$PATH"
# Any line that puts ~/.local/bin on PATH counts, however it spells home.
PATH_RE = re.compile(r"^[^#]*PATH=.*(~|\$HOME|\$\{HOME\}|%s)/\.local/bin" % re.escape(str(Path.home())), re.M)
MISE_RE = re.compile(r"^[^#]*mise activate", re.M)


def share_dir() -> Path:
    return Path.home() / ".local/share" / config.NAME


def init_sh_path() -> Path:
    return share_dir() / "init.sh"


def shims_dir() -> Path:
    return share_dir() / "shims"


def rc_block_content() -> str:
    p = "~/.local/share/curiousj-framekit/init.sh"
    return f"[[ -r {p} ]] && source {p}"


def distroboxrc_content() -> str:
    return ('case $PATH in\n'
            '  "$HOME/.local/share/curiousj-framekit/shims:"*) ;;\n'
            '  *) PATH="$HOME/.local/share/curiousj-framekit/shims:$PATH" ;;\n'
            'esac')


def completion(opts: Options, shell: str) -> str:
    """cjf's completion script for bash or zsh, as click generates it; ""
    when cjf can't be run (a test, say)."""
    env = dict(os.environ, _CJF_COMPLETE=f"{shell}_source")
    try:
        proc = subprocess.run([cmdline.cjf_path()], env=env, capture_output=True, text=True,
                              timeout=30)
    except (OSError, subprocess.TimeoutExpired):
        return ""
    return proc.stdout if proc.returncode == 0 else ""


def init_sh_text() -> str:
    """init.sh as shipped: it sources the completion files written beside
    it, so it is the same on every Frame."""
    return (resources.files("curiousj_framekit") / "shell" / "init.sh").read_text()


def completion_text(opts: Options, shell: str) -> str:
    script = completion(opts, shell)
    if not script:
        return ""
    return (f"# curiousj-framekit: cjf's {shell} completion, generated by `cjf init`;\n"
            f"# sourced from init.sh in {shell} only.\n" + script.rstrip("\n") + "\n")


def write_completion(opts: Options) -> bool:
    changed = False
    for shell in ("bash", "zsh"):
        text = completion_text(opts, shell)
        path = share_dir() / f"completion.{shell}"
        if text:
            changed |= cmdline.write_file(opts, path, text)
        elif path.exists():
            cmdline.say("skip", f"{cmdline.tilde(path)}: cjf gave no {shell} completion; left as is")
    return changed


def shim_text(name: str) -> str:
    return (resources.files("curiousj_framekit") / "shell" / "shims" / name).read_text()


def ensure_path_line(opts: Options, rc: Path) -> bool:
    text = rc.read_text() if rc.exists() else ""
    if PATH_RE.search(text):
        cmdline.say("ok", f"{cmdline.tilde(rc)}: ~/.local/bin on PATH")
        return False
    if text and not text.endswith("\n"):
        text += "\n"
    return cmdline.write_file(opts, rc, text + PATH_LINE + "\n")


def ensure_rc_block(opts: Options, rc: Path) -> bool:
    text = rc.read_text() if rc.exists() else ""
    new = blocks.ensure(text, "init", rc_block_content(), "top")
    if new == text:
        cmdline.say("ok", f"{cmdline.tilde(rc)}: sources init.sh")
        return False
    return cmdline.write_file(opts, rc, new)


def ensure_distroboxrc(opts: Options) -> bool:
    rc = Path.home() / ".distroboxrc"
    text = rc.read_text() if rc.exists() else ""
    new = blocks.ensure(text, "shims", distroboxrc_content())
    if new == text:
        cmdline.say("ok", f"{cmdline.tilde(rc)}: the shims on PATH")
        return False
    return cmdline.write_file(opts, rc, new)


def note_own_mise_line(rc: Path) -> None:
    if not rc.exists():
        return
    if MISE_RE.search(blocks.outside(rc.read_text())):
        cmdline.note(f"{cmdline.tilde(rc)} activates mise on a line of its own; init.sh does "
                     "that too (and skips itself when mise is active), so that line can go")


def run_init(opts: Options) -> dict[str, bool]:
    """Everything init does; the flags say what changed."""
    home = Path.home()
    changed = {"path": False, "init_sh": False, "shims": False, "rc": False,
               "distroboxrc": False, "conf": False, "entries": False}
    for rc in (home / ".bashrc", home / ".profile"):
        changed["path"] |= ensure_path_line(opts, rc)
    changed["init_sh"] = cmdline.write_file(opts, init_sh_path(), init_sh_text())
    changed["init_sh"] |= write_completion(opts)
    changed["shims"] = cmdline.write_file(opts, shims_dir() / "podman", shim_text("podman"),
                                          mode=0o755)
    rcs = [home / ".bashrc"]
    if (home / ".zshrc").exists():
        rcs.append(home / ".zshrc")
    for rc in rcs:
        changed["rc"] |= ensure_rc_block(opts, rc)
    changed["distroboxrc"] = ensure_distroboxrc(opts)
    rc_code = cursor.set_software(opts, "auto")
    changed["conf"] = rc_code == 100
    changed["entries"] = rc_code == 101
    for rc in rcs:
        note_own_mise_line(rc)
    return changed


def report(opts: Options, changed: dict[str, bool]) -> None:
    if not any(changed.values()):
        print("everything is in place")
        return
    if opts.check:
        print("run without --check to apply")
        return
    if changed["conf"]:
        print("reboot: environment.d is read at login, KWin takes the variable at its start")
    if changed["entries"]:
        print("the cursor size autostart entry runs at a desktop's next start")
    if changed["path"] or changed["init_sh"] or changed["rc"]:
        print("done: open a new shell")
    else:
        print("done")


@click.command(cls=cmdline.Command, help=__doc__,
               short_help="the base: PATH, init.sh, the shims, the rc blocks, the cursor fix")
@pass_options
def init(opts: Options) -> int:
    where.require_frame("init")
    report(opts, run_init(opts))
    return 0
