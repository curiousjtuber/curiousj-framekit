"""The shell files the kit ships or generates parse in the shells they
are for. bash is always here; zsh when installed."""

import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

from curiousj_framekit.cmdline import Options
from curiousj_framekit.install import init


def parses(shell: str, text: str) -> str:
    """"" when the shell accepts the file with -n, else its complaint."""
    with tempfile.NamedTemporaryFile("w", suffix=f".{shell}", delete=False) as f:
        f.write(text)
    proc = subprocess.run([shell, "-n", f.name], capture_output=True, text=True)
    Path(f.name).unlink()
    return proc.stderr.strip() if proc.returncode else ""


class InitSh(unittest.TestCase):
    def test_bash_parses_init_sh(self):
        self.assertEqual(parses("bash", init.init_sh_text()), "")

    @unittest.skipUnless(shutil.which("zsh"), "no zsh here")
    def test_zsh_parses_init_sh(self):
        self.assertEqual(parses("zsh", init.init_sh_text()), "")

    def fuse2_path(self, shell: str, home: Path, before: str = "") -> str:
        """LD_LIBRARY_PATH after init.sh's libfuse part ran in HOME, with
        HOME/usr standing in for the image's /usr and no container."""
        text = init.init_sh_text()
        start = text.index("_cjf_fuse2=")
        part = text[start:text.index("unset _cjf_fuse2", start)]
        self.assertIn("/usr/lib/libfuse.so.2", part)
        part = part.replace("/usr/lib/libfuse.so.2", f"{home}/usr/lib/libfuse.so.2")
        part = part.replace("/run/.containerenv", f"{home}/run/.containerenv")
        env = {"HOME": str(home), "PATH": "/usr/bin:/bin"}
        if before:
            env["LD_LIBRARY_PATH"] = before
        proc = subprocess.run([shell, "-c", part + '\nprintf %s "${LD_LIBRARY_PATH:-}"'],
                              capture_output=True, text=True, env=env)
        self.assertEqual(proc.stderr, "")
        return proc.stdout

    def test_fuse2_on_the_library_path(self):
        """Only with the package installed and none in the image, once."""
        shells = ["bash"] + (["zsh"] if shutil.which("zsh") else [])
        with tempfile.TemporaryDirectory() as tmp:
            home = Path(tmp)
            for shell in shells:
                self.assertEqual(self.fuse2_path(shell, home, "/opt/lib"), "/opt/lib")
            lib = home / ".local/lib/fuse2"
            lib.mkdir(parents=True)
            (lib / "libfuse.so.2").touch()
            for shell in shells:
                self.assertEqual(self.fuse2_path(shell, home), str(lib))
                self.assertEqual(self.fuse2_path(shell, home, "/opt/lib"), f"{lib}:/opt/lib")
                self.assertEqual(self.fuse2_path(shell, home, f"/opt/lib:{lib}"), f"/opt/lib:{lib}")
            (home / "usr/lib").mkdir(parents=True)
            (home / "usr/lib/libfuse.so.2").touch()
            for shell in shells:
                self.assertEqual(self.fuse2_path(shell, home, "/opt/lib"), "/opt/lib")

    def zsh_completion(self, home: Path, rc: str) -> str:
        """What an interactive zsh has for cjf after an rc file of `rc`,
        where INIT stands for sourcing init.sh, and its first prompt."""
        share = home / ".local/share/curiousj-framekit"
        share.mkdir(parents=True, exist_ok=True)
        (share / "init.sh").write_text(init.init_sh_text())
        (share / "completion.zsh").write_text("compdef _cjf_completion cjf\n")
        (home / ".zshrc").write_text(rc.replace("INIT", f"source {share}/init.sh") + "\n")
        env = {"HOME": str(home), "ZDOTDIR": str(home), "PATH": "/usr/bin:/bin", "TERM": "dumb"}
        proc = subprocess.run(
            ["zsh", "-i"], input='print -r -- "got=${_comps[cjf]-} hooks=${precmd_functions[*]}"\n',
            capture_output=True, text=True, env=env)
        return next((line for line in proc.stdout.splitlines() if line.startswith("got=")),
                    proc.stdout + proc.stderr)

    @unittest.skipUnless(shutil.which("zsh"), "no zsh here")
    def test_zsh_completion_whenever_compinit_runs(self):
        """init.sh is sourced from the top of ~/.zshrc, so compinit
        usually runs after it."""
        compinit = "autoload -Uz compinit && compinit -u -d $HOME/.zcompdump"
        with tempfile.TemporaryDirectory() as tmp:
            home = Path(tmp)
            self.assertEqual(self.zsh_completion(home, f"INIT\n{compinit}"),
                             "got=_cjf_completion hooks=")
            self.assertEqual(self.zsh_completion(home, f"{compinit}\nINIT"),
                             "got=_cjf_completion hooks=")
            self.assertEqual(self.zsh_completion(home, "INIT"), "got= hooks=")

    def test_shim_parses(self):
        self.assertEqual(parses("sh", init.shim_text("podman")), "")


class Completion(unittest.TestCase):
    """Generated by running cjf itself, so these need it on PATH (the uv
    venv's, under `uv run`)."""

    def test_bash_completion_parses_in_bash(self):
        text = init.completion_text(Options(), "bash")
        if not text:
            self.skipTest("cjf not runnable here")
        self.assertIn("complete", text)
        self.assertEqual(parses("bash", text), "")

    @unittest.skipUnless(shutil.which("zsh"), "no zsh here")
    def test_zsh_completion_parses_in_zsh(self):
        text = init.completion_text(Options(), "zsh")
        if not text:
            self.skipTest("cjf not runnable here")
        self.assertIn("compdef", text)
        self.assertEqual(parses("zsh", text), "")

    def test_the_zsh_script_is_not_bash(self):
        """The reason the files are separate: bash would choke on it."""
        text = init.completion_text(Options(), "zsh")
        if not text:
            self.skipTest("cjf not runnable here")
        self.assertNotEqual(parses("bash", text), "")
