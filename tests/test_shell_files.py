"""The shell files the kit ships or generates parse in the shells they
are for. bash is always here; zsh when installed."""

import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

from curiousj_framekit.cmdline import Options
from curiousj_framekit.install import init


def parses(shell: str, text: str) -> str:
    """"" when the shell accepts the file with -n, else its complaint."""
    with tempfile.NamedTemporaryFile("w", suffix=f".{shell}", delete=False) as f:
        f.write(text)
    proc = subprocess.run([shell, "-n", f.name], capture_output=True, text=True)
    Path(f.name).unlink()
    return proc.stderr.strip() if proc.returncode else ""


class InitSh(unittest.TestCase):
    def test_bash_parses_init_sh(self):
        self.assertEqual(parses("bash", init.init_sh_text()), "")

    @unittest.skipUnless(shutil.which("zsh"), "no zsh here")
    def test_zsh_parses_init_sh(self):
        self.assertEqual(parses("zsh", init.init_sh_text()), "")

    def test_shim_parses(self):
        self.assertEqual(parses("sh", init.shim_text("podman")), "")


class Completion(unittest.TestCase):
    """Generated by running cjf itself, so these need it on PATH (the uv
    venv's, under `uv run`)."""

    def test_bash_completion_parses_in_bash(self):
        text = init.completion_text(Options(), "bash")
        if not text:
            self.skipTest("cjf not runnable here")
        self.assertIn("complete", text)
        self.assertEqual(parses("bash", text), "")

    @unittest.skipUnless(shutil.which("zsh"), "no zsh here")
    def test_zsh_completion_parses_in_zsh(self):
        text = init.completion_text(Options(), "zsh")
        if not text:
            self.skipTest("cjf not runnable here")
        self.assertIn("compdef", text)
        self.assertEqual(parses("zsh", text), "")

    def test_the_zsh_script_is_not_bash(self):
        """The reason the files are separate: bash would choke on it."""
        text = init.completion_text(Options(), "zsh")
        if not text:
            self.skipTest("cjf not runnable here")
        self.assertNotEqual(parses("bash", text), "")
